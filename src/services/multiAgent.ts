import { MultiAgentRole, AgentPlanStep, Project, ProjectFile } from '../types';
import { generateAIResponse } from './aiProviders';
import { agentClient } from './agentClient';

export interface ArchitectPlanResponse {
  summary: string;
  architecture: string;
  techStack: string[];
  tasks: AgentPlanStep[];
}

export interface CoderResult {
  fileUpdates: { path: string; content: string; explanation: string }[];
  summary: string;
}

export interface DebuggerResult {
  rootCause: string;
  proposedFix: string;
  fileUpdates: { path: string; content: string }[];
}

export interface TesterResult {
  testCode?: string;
  testFilePath?: string;
  executedOnAgent: boolean;
  passed: boolean;
  exitCode: number;
  output: string;
}

// 1. ARCHITECT AGENT
export async function runArchitectAgent(
  userRequest: string,
  project: Project
): Promise<ArchitectPlanResponse> {
  const fileList = project.files.map(f => `- ${f.path} (${f.language})`).join('\n');

  const systemPrompt = `You are the ARCHITECT Agent in PocketForge AI.
Your purpose:
1. Deeply understand the user's mobile/web software request.
2. Formulate a clean, modular project plan with minimal memory & CPU usage suitable for phone execution.
3. Deconstruct the implementation into concrete, sequential development steps.

You MUST respond strictly with valid JSON conforming to this schema (no extra prose outside JSON):
{
  "summary": "High-level summary of proposed changes",
  "architecture": "Architecture and design explanation",
  "techStack": ["library1", "tool2"],
  "tasks": [
    {
      "id": "task-1",
      "title": "Short title",
      "description": "Specific action to perform",
      "targetFile": "path/to/file.ext",
      "status": "pending"
    }
  ]
}`;

  const userPrompt = `Current Project: ${project.name} (Template: ${project.template})
Existing Files in Project:
${fileList || '(Empty project)'}

User Request:
${userRequest}`;

  const res = await generateAIResponse([
    { role: 'user', content: userPrompt }
  ], systemPrompt);

  try {
    const jsonMatch = res.text.match(/\{[\s\S]*\}/);
    if (jsonMatch) {
      const parsed = JSON.parse(jsonMatch[0]);
      return {
        summary: parsed.summary || 'Project Architecture Plan',
        architecture: parsed.architecture || '',
        techStack: parsed.techStack || [],
        tasks: (parsed.tasks || []).map((t: any, idx: number) => ({
          id: t.id || `task-${idx + 1}`,
          title: t.title || `Task ${idx + 1}`,
          description: t.description || '',
          targetFile: t.targetFile,
          status: 'pending' as const
        }))
      };
    }
  } catch (e) {
    console.error('Failed to parse Architect JSON:', e);
  }

  // Fallback if model did not return pure JSON
  return {
    summary: 'Plan generated by Architect',
    architecture: res.text,
    techStack: [],
    tasks: [
      {
        id: 'task-1',
        title: 'Implement requested feature',
        description: userRequest,
        status: 'pending'
      }
    ]
  };
}

// 2. CODER AGENT
export async function runCoderAgent(
  task: AgentPlanStep,
  project: Project,
  contextNote?: string
): Promise<CoderResult> {
  const targetFileObj = task.targetFile ? project.files.find(f => f.path === task.targetFile) : null;
  const otherFiles = project.files
    .filter(f => f.path !== task.targetFile)
    .slice(0, 5) // limit context for low mobile bandwidth
    .map(f => `--- File: ${f.path} ---\n${f.content.slice(0, 800)}`)
    .join('\n\n');

  const systemPrompt = `You are the CODER Agent in PocketForge AI.
Your purpose:
1. Implement the assigned development task with clean, bug-free, mobile-optimized code.
2. Return complete, ready-to-run file contents.

You MUST respond in this format:
For each file you modify or create, provide:
FILE: <relative_path>
\`\`\`<language>
<full_file_content>
\`\`\`
EXPLANATION: <brief note on changes>`;

  const userPrompt = `Task Title: ${task.title}
Task Description: ${task.description}
Target File: ${task.targetFile || 'Determine appropriate file'}
${contextNote ? `Special Context / Architecture: ${contextNote}\n` : ''}

${targetFileObj ? `Current contents of ${targetFileObj.path}:\n\`\`\`${targetFileObj.language}\n${targetFileObj.content}\n\`\`\`\n` : ''}
Relevant Context from Project:
${otherFiles}`;

  const res = await generateAIResponse([
    { role: 'user', content: userPrompt }
  ], systemPrompt);

  const fileUpdates: { path: string; content: string; explanation: string }[] = [];
  const fileRegex = /FILE:\s*([^\r\n]+)\r?\n```[a-zA-Z0-9_-]*\r?\n([\s\S]*?)```/g;
  let match;

  while ((match = fileRegex.exec(res.text)) !== null) {
    const filePath = match[1].trim();
    const content = match[2];
    fileUpdates.push({
      path: filePath,
      content,
      explanation: `Updated ${filePath} according to task`
    });
  }

  // If no formatted block found, attempt to salvage targetFile
  if (fileUpdates.length === 0 && task.targetFile) {
    const codeMatch = res.text.match(/```[a-zA-Z0-9_-]*\r?\n([\s\S]*?)```/);
    if (codeMatch) {
      fileUpdates.push({
        path: task.targetFile,
        content: codeMatch[1],
        explanation: 'Generated code from task output'
      });
    }
  }

  return {
    fileUpdates,
    summary: res.text.replace(/FILE:[\s\S]*?```/g, '').trim() || 'Code implementation completed.'
  };
}

// 3. DEBUGGER AGENT
export async function runDebuggerAgent(
  errorMessage: string,
  project: Project,
  relatedFilePath?: string
): Promise<DebuggerResult> {
  const targetFile = relatedFilePath ? project.files.find(f => f.path === relatedFilePath) : null;
  const projectSnippet = project.files
    .slice(0, 4)
    .map(f => `--- File: ${f.path} ---\n${f.content.slice(0, 1000)}`)
    .join('\n\n');

  const systemPrompt = `You are the DEBUGGER Agent in PocketForge AI.
Your purpose:
1. Analyze compiler, runtime, or terminal error logs.
2. Identify the root cause accurately.
3. Propose minimal, exact fixes.

Format your response strictly as:
ROOT_CAUSE: <explanation>
FIX_SUMMARY: <what was changed>
FILE: <file_path>
\`\`\`<language>
<repaired_full_file_content>
\`\`\``;

  const userPrompt = `Runtime / Terminal Error:
${errorMessage}

${targetFile ? `Suspected File (${targetFile.path}):\n\`\`\`\n${targetFile.content}\n\`\`\`\n` : ''}
Project Files:
${projectSnippet}`;

  const res = await generateAIResponse([
    { role: 'user', content: userPrompt }
  ], systemPrompt);

  const fileUpdates: { path: string; content: string }[] = [];
  const fileRegex = /FILE:\s*([^\r\n]+)\r?\n```[a-zA-Z0-9_-]*\r?\n([\s\S]*?)```/g;
  let match;

  while ((match = fileRegex.exec(res.text)) !== null) {
    fileUpdates.push({
      path: match[1].trim(),
      content: match[2]
    });
  }

  const causeMatch = res.text.match(/ROOT_CAUSE:\s*([\s\S]*?)(?=FIX_SUMMARY:|FILE:|$)/);
  const fixMatch = res.text.match(/FIX_SUMMARY:\s*([\s\S]*?)(?=FILE:|$)/);

  return {
    rootCause: causeMatch ? causeMatch[1].trim() : 'Error analyzed by Debugger',
    proposedFix: fixMatch ? fixMatch[1].trim() : 'Applied surgical patch',
    fileUpdates
  };
}

// 4. TESTER AGENT
export async function runTesterAgent(
  project: Project,
  executeOnTermux: boolean = false
): Promise<TesterResult> {
  const isPython = project.template === 'python-app' || project.template === 'flask-api';
  const testCmd = isPython ? 'python -m unittest discover -s . -p "test_*.py"' : 'npm test';

  if (executeOnTermux) {
    try {
      const res = await agentClient.execCommand(testCmd, project.name, 25000);
      return {
        executedOnAgent: true,
        passed: res.exitCode === 0,
        exitCode: res.exitCode,
        output: res.stdout || res.stderr || `Exit code ${res.exitCode}`
      };
    } catch (err: any) {
      return {
        executedOnAgent: true,
        passed: false,
        exitCode: 1,
        output: `Local agent execution failed: ${err.message}`
      };
    }
  }

  // If agent is offline, generate tests with AI
  const systemPrompt = `You are the TESTER Agent in PocketForge AI.
Design a concise unit test file for this project.
Return the test code in a single markdown block with the filename at top:
FILE: test_suite.js (or test_suite.py)
\`\`\`
<test_code>
\`\`\``;

  const res = await generateAIResponse([
    { role: 'user', content: `Project: ${project.name} (${project.template})\nFiles:\n${project.files.map(f => f.path).join(', ')}` }
  ], systemPrompt);

  const fileMatch = res.text.match(/FILE:\s*([^\r\n]+)\r?\n```[a-zA-Z0-9_-]*\r?\n([\s\S]*?)```/);

  return {
    testCode: fileMatch ? fileMatch[2] : undefined,
    testFilePath: fileMatch ? fileMatch[1].trim() : (isPython ? 'test_app.py' : 'test.js'),
    executedOnAgent: false,
    passed: true,
    exitCode: 0,
    output: 'Test suite generated. Run via Termux Local Agent to execute against runtime.'
  };
}
